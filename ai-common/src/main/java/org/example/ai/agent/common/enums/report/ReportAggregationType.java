package org.example.ai.agent.common.enums.report;

/**
 * 报告计算字段的汇总方式。
 */
public enum ReportAggregationType {

    /**
     * 求和。
     */
    SUM,

    /**
     * 平均值。
     */
    AVG,

    /**
     * 有效值数量。
     */
    COUNT,

    /**
     * 最大值。
     */
    MAX,

    /**
     * 最小值。
     */
    MIN
}